logger = logging.getLogger(__name__)
router = APIRouter()
UPLOAD_CHUNK_SIZE = 1024 * 1024
_INVALID_FILENAME_CHARS = re.compile(r"[\x00-\x1f\x7f]")


def _canonical_task_id(task_id: str) -> str:
    """Accept only UUID task IDs generated by this API."""
    try:
        return str(uuid.UUID(task_id))
    except (AttributeError, TypeError, ValueError) as exc:
        raise HTTPException(status_code=404, detail="Analysis task not found") from exc


def _owned_task(task_id: str, db: DB, current_user: CurrentUser) -> AnalysisRun:
    """Resolve ownership through the persisted run and its parent session."""
    canonical_id = _canonical_task_id(task_id)
    stmt = select(AnalysisRun).where(AnalysisRun.task_id == canonical_id).limit(2)
    matches = list(db.scalars(stmt).all())
    if len(matches) != 1:
        raise HTTPException(status_code=404, detail="Analysis task not found")

    run = matches[0]
    session = crud.get_session(db, run.session_id)
    if (
        session is None
        or str(run.requested_by) != str(current_user.id)
        or str(session.user_id) != str(current_user.id)
    ):
        raise HTTPException(status_code=404, detail="Analysis task not found")
    return run


def _create_task_owner(
    db: DB,
    *,
    user_id: str,
    task_id: str,
    source_type: str,
    source_path: str,
    name: str,
    original_filename: str | None = None,
) -> AnalysisRun:
    """Create the DB ownership chain before dispatching a legacy task."""
    session = SessionModel(
        user_id=user_id,
        name=name[:255],
        source_type=source_type,
        source_path=source_path,
        status="queued",
        dataset_meta=(
            {"original_filename": original_filename}
            if original_filename
            else {}
        ),
    )
    db.add(session)
    db.flush()
    run = AnalysisRun(
        session_id=session.id,
        requested_by=user_id,
        task_id=task_id,
        status="queued",
        config_json={"legacy_analysis": True},
    )
    db.add(run)
    db.commit()
    db.refresh(run)
    return run


def _remove_task_owner(db: DB, run: AnalysisRun) -> None:
    """Remove an unstarted owner record if queue submission failed."""
    try:
        session = crud.get_session(db, run.session_id)
        db.delete(run)
        if session is not None:
            db.delete(session)
        db.commit()
    except Exception:
        db.rollback()
        logger.warning("Could not remove an unqueued legacy analysis record")


def _safe_upload_name(raw_name: str | None) -> tuple[str, str]:
    """Return a display basename and supported suffix, independent of client path."""
    if not raw_name or _INVALID_FILENAME_CHARS.search(raw_name):
        raise HTTPException(status_code=400, detail="A valid dataset filename is required")
    basename = PurePosixPath(raw_name.replace("\\", "/")).name
    if basename in {"", ".", ".."} or len(basename) > 255:
        raise HTTPException(status_code=400, detail="Invalid dataset filename")
    extension = Path(basename).suffix.lower()
    if extension not in SUPPORTED_EXTENSIONS:
        raise HTTPException(status_code=400, detail="Unsupported dataset file type")
    return basename, extension


def _validate_upload_content(prefix: bytes, extension: str) -> None:
    """Reject obvious extension/content mismatches using only a small prefix."""
    if extension == ".xlsx" and not prefix.startswith(b"PK\x03\x04"):
        raise HTTPException(status_code=400, detail="File contents do not match the dataset type")
    if extension == ".xls" and not prefix.startswith(bytes.fromhex("D0CF11E0A1B11AE1")):
        raise HTTPException(status_code=400, detail="File contents do not match the dataset type")
    if extension not in {".xlsx", ".xls"}:
        if b"\x00" in prefix:
            raise HTTPException(status_code=400, detail="File contents do not match the dataset type")
        try:
            codecs.getincrementaldecoder("utf-8-sig")().decode(prefix, final=False)
        except UnicodeDecodeError as exc:
            raise HTTPException(
                status_code=400,
                detail="Dataset text must use UTF-8 encoding",
            ) from exc


def _remove_uploaded_file(path: Path | None) -> None:
    if path is None:
        return
    try:
        path.unlink(missing_ok=True)
    except OSError:
        logger.warning("Could not remove a temporary legacy upload")


def _queue_task(
    *,
    db: DB,
    run: AnalysisRun,
    task_id: str,
    args: list,
    upload_path: Path | None = None,
) -> TaskResponse:
    try:
        analyze_dataset.apply_async(args=args, task_id=task_id)
    except Exception as exc:
        _remove_task_owner(db, run)
        _remove_uploaded_file(upload_path)
        logger.warning("Legacy analysis task could not be queued (error_type=%s)", type(exc).__name__)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Analysis could not be queued. Please try again.",
        ) from exc
    return TaskResponse(task_id=task_id)


@router.post("/analyze/upload", response_model=TaskResponse)
async def analyze_upload(
    db: DB,
    current_user: CurrentUser,
    file: UploadFile = File(...),
    target_column: str | None = Form(None),
) -> TaskResponse:
    """Stream a supported dataset into storage and queue its analysis."""
    partial_path: Path | None = None
    destination: Path | None = None
    try:
        original_filename, extension = _safe_upload_name(file.filename)
        task_id = str(uuid.uuid4())
        upload_root = settings.UPLOAD_DIR.resolve()
        upload_root.mkdir(parents=True, exist_ok=True)
        partial_path = upload_root / f".{task_id}.part"
        destination = upload_root / f"{task_id}{extension}"
        max_bytes = settings.MAX_FILE_SIZE_MB * 1024 * 1024
        total_bytes = 0
        prefix = bytearray()

        try:
            destination.resolve(strict=False).relative_to(upload_root)
        except (OSError, RuntimeError, ValueError) as exc:
            raise HTTPException(status_code=400, detail="Invalid upload destination") from exc

        with partial_path.open("xb") as output:
            while chunk := await file.read(UPLOAD_CHUNK_SIZE):
                total_bytes += len(chunk)
                if total_bytes > max_bytes:
                    raise HTTPException(
                        status_code=413,
                        detail=f"File exceeds {settings.MAX_FILE_SIZE_MB} MB.",
                    )
                output.write(chunk)
                if len(prefix) < 8192:
                    prefix.extend(chunk[: 8192 - len(prefix)])

        if total_bytes == 0:
            raise HTTPException(status_code=400, detail="The uploaded dataset is empty")
        _validate_upload_content(bytes(prefix), extension)
        os.replace(partial_path, destination)
        run = _create_task_owner(
            db,
            user_id=str(current_user.id),
            task_id=task_id,
            source_type="upload",
            source_path=str(destination),
            name=original_filename,
            original_filename=original_filename,
        )
        return _queue_task(
            db=db,
            run=run,
            task_id=task_id,
            args=["upload", str(destination), target_column],
            upload_path=destination,
        )
    except HTTPException:
        _remove_uploaded_file(partial_path)
        raise
    except Exception as exc:
        db.rollback()
        _remove_uploaded_file(partial_path)
        _remove_uploaded_file(destination)
        logger.warning("Legacy upload failed (error_type=%s)", type(exc).__name__)
        raise HTTPException(status_code=400, detail="The uploaded dataset could not be accepted") from exc
    finally:
        await file.close()


@router.post("/analyze/url", response_model=TaskResponse)
async def analyze_url(
    req: AnalyzeURLRequest,
    db: DB,
    current_user: CurrentUser,
) -> TaskResponse:
    """Queue URL loading with an owner record tied to a session."""
    task_id = str(uuid.uuid4())
    url_name = PurePosixPath(unquote(urlsplit(req.url).path).replace("\\", "/")).name
    url_name = _INVALID_FILENAME_CHARS.sub("_", url_name)[:255] or "URL dataset"
    try:
        run = _create_task_owner(
            db,
            user_id=str(current_user.id),
            task_id=task_id,
            source_type="url",
            source_path=req.url,
            name=url_name,
            original_filename=url_name,
        )
    except Exception as exc:
        db.rollback()
        logger.warning("Legacy URL analysis record could not be created (error_type=%s)", type(exc).__name__)
        raise HTTPException(status_code=503, detail="Analysis could not be started") from exc
    return _queue_task(
        db=db,
        run=run,
        task_id=task_id,
        args=["url", req.url, req.target_column],
    )


@router.get("/status/{task_id}", response_model=TaskStatus)
async def get_status(task_id: str, db: DB, current_user: CurrentUser) -> TaskStatus:
    run = _owned_task(task_id, db, current_user)
    try:
        result = AsyncResult(run.task_id, app=celery_app)
        state = result.state
        meta = result.info if isinstance(result.info, dict) else {}
    except Exception as exc:
        logger.warning("Legacy task status unavailable (error_type=%s)", type(exc).__name__)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Analysis status is temporarily unavailable",
        ) from exc

    if state == "PENDING":
        return TaskStatus(task_id=run.task_id, status="queued")
    if state in ("PROGRESS", "STARTED"):
        return TaskStatus(
            task_id=run.task_id,
            status="running",
            step=meta.get("step"),
            progress=meta.get("progress"),
        )
    if state == "SUCCESS":
        if meta.get("status") == "failed":
            return TaskStatus(
                task_id=run.task_id,
                status="failed",
                error="Analysis task failed. Check server logs for details.",
            )
        safe_fields = {
            "analysis_status",
            "report_status",
            "best_model",
            "task_type",
            "target_column",
            "memory_summary",
        }
        safe_result = {key: meta[key] for key in safe_fields if key in meta}
        return TaskStatus(task_id=run.task_id, status="done", result=safe_result)
    return TaskStatus(
        task_id=run.task_id,
        status="failed",
        error="Analysis task failed. Check server logs for details.",
    )


def _latest_task_artifact(
    run: AnalysisRun,
    db: DB,
    artifact_type: str,
    permitted_root: Path,
    label: str,
) -> Path:
    artifacts = [
        item
        for item in crud.list_artifacts(db, run.session_id)
        if item.artifact_type == artifact_type
    ]
    if not artifacts:
        raise HTTPException(status_code=404, detail=f"{label} not found")
    return resolve_artifact_path(
        artifacts[-1].file_path,
        artifact_label=label,
        permitted_root=permitted_root,
    )


@router.get("/download/report/{task_id}")
async def download_report(
    task_id: str,
    db: DB,
    current_user: CurrentUser,
) -> FileResponse:
    run = _owned_task(task_id, db, current_user)
    path = _latest_task_artifact(run, db, "report", settings.REPORT_DIR, "Report")
    return FileResponse(
        path,
        media_type="application/pdf",
        filename=f"report_{run.task_id}.pdf",
    )


